// MLXModel.swift — a model downloaded to this Mac, run on Apple's MLX.
//
// Loaded from its folder (the one Author and Knowledge Space share, or one
// the person chose), at temperature 0 with a fixed seed so a run can be
// repeated, and pinned by the fingerprint of all its files.

import Foundation
import MLXLLM
import MLXLMCommon
import Tokenizers
import ModelCheck

final class MLXModel: StreamingCheckedModel, @unchecked Sendable {

    let folder: URL
    let name: String
    /// SHA-256 over all the model's files, and their size.
    let fingerprint: (hash: String, size: Int64)?
    private var container: ModelContainer?

    init(folder: URL, name: String, fingerprint: (hash: String, size: Int64)?) {
        self.folder = folder
        self.name = name
        self.fingerprint = fingerprint
    }

    var identity: ModelIdentity {
        ModelIdentity(name: name, provider: "local", sha256: fingerprint?.hash, fileSize: fingerprint?.size,
                      quantisation: Self.quantisation(of: folder),
                      runtime: .init(name: "MLX Swift LM", version: "3.32"),
                      settings: ["temperature": "0", "seed": "7", "maxTokens": "800"])
    }

    /// "4-bit" and so on, from the model's configuration.
    static func quantisation(of folder: URL) -> String? {
        guard let data = try? Data(contentsOf: folder.appendingPathComponent("config.json")),
              let json = try? JSONSerialization.jsonObject(with: data) as? [String: Any] else { return nil }
        let q = (json["quantization"] ?? json["quantization_config"]) as? [String: Any]
        if let bits = q?["bits"] as? Int { return "\(bits)-bit" }
        return json["torch_dtype"] as? String
    }

    private func load() async throws -> ModelContainer {
        if let container { return container }
        let loaded = try await LLMModelFactory.shared.loadContainer(from: folder, using: TransformersTokenizerLoader())
        container = loaded
        return loaded
    }

    func reply(system: String?, conversation: [Turn]) async throws -> String {
        try await reply(system: system, conversation: conversation) { _ in }
    }

    func reply(system: String?, conversation: [Turn], onChunk: @escaping @Sendable (String) -> Void) async throws -> String {
        let container = try await load()
        var history: [Chat.Message] = []
        if let system { history.append(.system(system)) }
        for turn in conversation.dropLast() {
            history.append(turn.role == .user ? .user(turn.text) : .assistant(turn.text))
        }
        let session = ChatSession(container, history: history,
                                  generateParameters: GenerateParameters(maxTokens: 800, temperature: 0, seed: 7),
                                  additionalContext: ["enable_thinking": false])
        var text = ""
        for try await chunk in session.streamResponse(to: conversation.last?.text ?? "", images: [], videos: []) {
            text += chunk
            onChunk(chunk)
        }
        // A model that thinks aloud first: only its answer is scored.
        return text.replacingOccurrences(of: #"(?s)<think>.*?</think>"#, with: "", options: .regularExpression)
            .trimmingCharacters(in: .whitespacesAndNewlines)
    }
}

/// swift-transformers' tokenizer, as MLX wants it — written out rather than
/// generated by mlx-swift-lm's macro, so building needs no macro approval.
struct TransformersTokenizerLoader: MLXLMCommon.TokenizerLoader {
    func load(from directory: URL) async throws -> any MLXLMCommon.Tokenizer {
        TokenizerBridge(try await AutoTokenizer.from(modelFolder: directory))
    }
}

struct TokenizerBridge: MLXLMCommon.Tokenizer {
    private let upstream: any Tokenizers.Tokenizer
    init(_ upstream: any Tokenizers.Tokenizer) { self.upstream = upstream }

    func encode(text: String, addSpecialTokens: Bool) -> [Int] { upstream.encode(text: text, addSpecialTokens: addSpecialTokens) }
    func decode(tokenIds: [Int], skipSpecialTokens: Bool) -> String { upstream.decode(tokens: tokenIds, skipSpecialTokens: skipSpecialTokens) }
    func convertTokenToId(_ token: String) -> Int? { upstream.convertTokenToId(token) }
    func convertIdToToken(_ id: Int) -> String? { upstream.convertIdToToken(id) }
    var bosToken: String? { upstream.bosToken }
    var eosToken: String? { upstream.eosToken }
    var unknownToken: String? { upstream.unknownToken }

    func applyChatTemplate(messages: [[String: any Sendable]], tools: [[String: any Sendable]]?,
                           additionalContext: [String: any Sendable]?) throws -> [Int] {
        do {
            return try upstream.applyChatTemplate(messages: messages, tools: tools, additionalContext: additionalContext)
        } catch Tokenizers.TokenizerError.missingChatTemplate {
            throw MLXLMCommon.TokenizerError.missingChatTemplate
        }
    }
}
